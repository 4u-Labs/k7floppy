// Normaliza acentos PT-BR para ASCII legível no estilo TK 2000
export function normalizeTkChar(ch) {
  const map = {
    'Á': 'A', 'À': 'A', 'Ã': 'A', 'Â': 'A',
    'É': 'E', 'Ê': 'E',
    'Í': 'I',
    'Ó': 'O', 'Õ': 'O', 'Ô': 'O',
    'Ú': 'U', 'Ü': 'U',
    'Ç': 'C',
  };
  const upper = ch.toUpperCase();
  if (FONT_5X7[upper]) return upper;
  if (map[upper]) return map[upper];
  return FONT_5X7[ch] ? ch : ' ';
}
